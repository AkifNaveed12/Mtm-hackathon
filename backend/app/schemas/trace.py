from typing import Literal, List
from pydantic import BaseModel, Field

AreaTag = Literal["reading", "venue", "schedule", "food", "judging", "budget"]

class TraceEntry(BaseModel):
    call_number: int = Field(..., description="Chronological sequential model call index")
    model_name: str = Field(..., description="Exact model name used")
    area_tag: AreaTag = Field(..., description="Permitted area tag")
    input: str = Field(..., description="Prompt or message input fed to the model")
    output: str = Field(..., description="Raw output generated by the model")
    prompt_tokens: int = Field(0, description="Reported input prompt tokens")
    completion_tokens: int = Field(0, description="Reported completion tokens")
    total_tokens: int = Field(0, description="Total tokens for this call")

class TraceLog(BaseModel):
    entries: List[TraceEntry] = Field(default_factory=list)
    total_calls: int = 0
    total_prompt_tokens: int = 0
    total_completion_tokens: int = 0
    overall_total_tokens: int = 0
